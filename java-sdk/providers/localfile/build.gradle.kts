import com.diffplug.gradle.spotless.SpotlessExtension
import org.gradle.process.CommandLineArgumentProvider

plugins {
    `java-library`
    id("airflow-jvm-conventions")
    id("airflow-publish")
}

val mockkVersion: String by project

// The SDK is shared: the Dag or the Java runtime that loads this provider already has it.
dependencies {
    compileOnly(project(":sdk"))

    testImplementation(project(":sdk"))
    testImplementation(kotlin("test"))
    testImplementation("io.mockk:mockk:$mockkVersion")
    testImplementation("io.mockk:mockk-agent:$mockkVersion")
}

java {
    withSourcesJar() // Required by Maven Central.
}

// The JAR of the provider directory under java_providers_path is named after the artifact.
base {
    archivesName = "airflow-provider-java-localfile"
}

// The wrappers under org/apache/airflow/providers/java are generated by
// scripts/ci/lang_sdk_providers/generate_java_wrappers.py, and a test keeps them up to date.
configure<SpotlessExtension> {
    java {
        targetExclude("src/main/java/org/apache/airflow/providers/java/**")
    }
}

// The SDK with the dependencies it runs with, for the tasks that run its classes.
val sdkRuntime by configurations.creating {
    isCanBeConsumed = false
    isCanBeResolved = true
    attributes {
        attribute(Usage.USAGE_ATTRIBUTE, objects.named(Usage.JAVA_RUNTIME))
        attribute(Category.CATEGORY_ATTRIBUTE, objects.named(Category.LIBRARY))
        attribute(LibraryElements.LIBRARY_ELEMENTS_ATTRIBUTE, objects.named(LibraryElements.JAR))
    }
}

dependencies {
    sdkRuntime(project(":sdk"))
    sdkRuntime(project(":jpl"))
}

// The spec of the provider's operators, which the other SDKs and the Python wrapper are generated from.
val operatorSpecFile =
    rootProject.layout.projectDirectory.file("../providers/java/localfile/_generated/lang_sdk_operators.json")

fun registerOperatorSpecTask(
    taskName: String,
    taskDescription: String,
    check: Boolean,
) = tasks.register<JavaExec>(taskName) {
    group = "build"
    description = taskDescription
    dependsOn(tasks.classes)
    classpath(sourceSets.main.get().output, sdkRuntime)
    mainClass = "org.apache.airflow.sdk.provider.SpecGenerator"
    val classesDirs =
        sourceSets.main
            .get()
            .output.classesDirs
    val specFile = operatorSpecFile
    val providerVersion = project.version.toString()
    argumentProviders.add(
        CommandLineArgumentProvider {
            buildList {
                classesDirs.files.forEach { addAll(listOf("--classes", it.absolutePath)) }
                addAll(
                    listOf(
                        "--provider-id",
                        "java.localfile",
                        "--package",
                        "apache-airflow-providers-java-localfile",
                        "--version",
                        providerVersion,
                        "--provider-dir",
                        "java-localfile",
                        "--output",
                        specFile.asFile.absolutePath,
                    ),
                )
                if (check) add("--check")
            }
        },
    )
}

registerOperatorSpecTask(
    "generateOperatorSpec",
    "Writes providers/java/localfile/_generated/lang_sdk_operators.json from the operators' annotations.",
    check = false,
)
val checkOperatorSpec =
    registerOperatorSpecTask(
        "checkOperatorSpec",
        "Fails when the committed operator spec is not what the operators' annotations generate.",
        check = true,
    )
tasks.named("check") { dependsOn(checkOperatorSpec) }

// A java_providers_path directory for a Java coordinator: the SDK, and this provider in a directory of its own.
tasks.register<Sync>("installProviderRuntime") {
    group = "build"
    description = "Assembles a java_providers_path directory with the SDK and this provider."
    destinationDir =
        layout.buildDirectory
            .dir("java-providers")
            .get()
            .asFile
    into("sdk") { from(sdkRuntime) }
    into("java-localfile") { from(tasks.jar) }
}

tasks.withType<Test> {
    useJUnitPlatform()
    jvmArgs("-Djdk.attach.allowAttachSelf=true")
    val classesDirs =
        sourceSets.main
            .get()
            .output.classesDirs
    systemProperty("airflow.operatorClassesDirs", classesDirs.files.joinToString(File.pathSeparator))
    systemProperty("airflow.operatorSpecFile", operatorSpecFile.asFile.absolutePath)
}

publishing {
    publications {
        create<MavenPublication>("mavenJava") {
            artifactId = "airflow-provider-java-localfile"
            from(components["java"])
            pom {
                name = "Apache Airflow Provider: Java local file operators"
                description =
                    "Operators that create, write, check and delete local files, implemented in Java. " +
                    "Python Dags and Dags of every language SDK can use them; a Java coordinator runs them."
            }
        }
    }
}
