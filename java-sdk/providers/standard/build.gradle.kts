import com.diffplug.gradle.spotless.SpotlessExtension

plugins {
    `java-library`
    id("airflow-jvm-conventions")
    id("airflow-publish")
}

// The SDK is shared: the Dag that uses these wrappers already has it.
dependencies {
    compileOnly(project(":sdk"))
}

java {
    withSourcesJar() // Required by Maven Central.
}

// Every source file is generated by scripts/ci/lang_sdk_providers/generate_java_wrappers.py, and a
// test keeps them up to date, so the formatter has nothing to say about them.
configure<SpotlessExtension> {
    java {
        targetExclude("src/main/java/**")
    }
}

publishing {
    publications {
        create<MavenPublication>("mavenJava") {
            artifactId = "airflow-provider-standard"
            from(components["java"])
            pom {
                name = "Apache Airflow Provider: standard"
                description =
                    "Typed wrappers of the operators and sensors of apache-airflow-providers-standard, " +
                    "for Dags written in Java. A Python worker runs them."
            }
        }
    }
}
